# Database — на Vercel SQLite недоступен для записи; нужен PostgreSQL (DATABASE_URL).
def _database_from_url(url: str) -> dict:
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    parsed = urllib.parse.urlparse(url)
    name = urllib.parse.unquote(parsed.path.lstrip("/"))
    cfg = {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": name,
        "USER": urllib.parse.unquote(parsed.username or ""),
        "PASSWORD": urllib.parse.unquote(parsed.password or ""),
        "HOST": parsed.hostname or "",
        "PORT": str(parsed.port or 5432),
        "OPTIONS": {},
    }
    query = urllib.parse.parse_qs(parsed.query)
    if query.get("sslmode"):
        cfg["OPTIONS"]["sslmode"] = query["sslmode"][0]
    return cfg


def _resolve_database_url() -> str | None:
    """Совместимость с Neon/Vercel и ручными именами переменных."""
    for key in (
        "DATABASE_URL",
        "POSTGRES_URL",
        "POSTGRES_PRISMA_URL",
    ):
        v = (os.environ.get(key) or "").strip()
        if v:
            return v
    return None


